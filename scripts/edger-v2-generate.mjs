#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";

import { validateEdgerV2PolicyModel } from "../src/ai/v2/policy.js";

function parseArgs(argv) {
  const parsed = {
    model: null,
    out: "src/ai/generated/edgerPolicyV2Shadow.js",
  };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--model" && argv[index + 1]) {
      parsed.model = argv[++index];
    } else if (argv[index] === "--out" && argv[index + 1]) {
      parsed.out = argv[++index];
    }
  }
  if (!parsed.model) {
    throw new Error("--model is required");
  }
  return parsed;
}

const args = parseArgs(process.argv.slice(2));
const model = validateEdgerV2PolicyModel(
  JSON.parse(fs.readFileSync(args.model, "utf8")),
);
const output = path.resolve(args.out);
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(
  output,
  `// Generated by scripts/edger-v2-generate.mjs from ${args.model}.\n` +
    "// Shadow-only until every v2 promotion gate passes.\n" +
    `export const EDGER_POLICY_V2_SHADOW_MODEL = ${JSON.stringify(model, null, 2)};\n\n` +
    "export default EDGER_POLICY_V2_SHADOW_MODEL;\n",
);
console.log(`wrote ${output}`);
