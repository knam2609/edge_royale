#!/usr/bin/env node

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { validateEdgerV2PolicyModel } from "../src/ai/v2/policy.js";
import {
  EDGER_V2_EVALUATION_REPORT_SCHEMA,
  createEdgerV2ReferenceReport,
} from "./edger-v2-evaluation-core.mjs";

const PROMOTED_MODEL = "artifacts/edger-training/promoted/edger_policy_current.json";
const PROMOTED_REPORT = "artifacts/edger-training/promoted/edger_policy_current_report.json";
const PROMOTED_REFERENCE = "artifacts/edger-training/promoted/edger_policy_current_reference.json";
const GENERATED_MODEL = "src/ai/generated/edgerPolicyCurrent.js";
const REQUIRED_GATES = [
  "acceptance_profile",
  "schema_and_size",
  "pytorch_js_parity",
  "champion",
  "anchors",
  "weak_baselines",
  "frozen_league",
  "safety",
  "tactical_scenarios",
  "replay",
  "generated_js_timing",
  "full_test_suite",
  "browser_smoke",
];

function parseArgs(argv) {
  const parsed = { model: null, report: null };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--model" && argv[index + 1]) {
      parsed.model = argv[++index];
    } else if (argv[index] === "--report" && argv[index + 1]) {
      parsed.report = argv[++index];
    }
  }
  if (!parsed.model || !parsed.report) {
    throw new Error("--model and --report are required");
  }
  return parsed;
}

function sha256File(filePath) {
  return createHash("sha256").update(fs.readFileSync(filePath)).digest("hex");
}

function canonical(value) {
  if (Array.isArray(value)) {
    return value.map(canonical);
  }
  if (!value || typeof value !== "object") {
    return value;
  }
  return Object.keys(value).sort().reduce((result, key) => {
    result[key] = canonical(value[key]);
    return result;
  }, {});
}

function writeJson(filePath, value) {
  fs.mkdirSync(path.dirname(path.resolve(filePath)), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(canonical(value), null, 2)}\n`);
}

const args = parseArgs(process.argv.slice(2));
const model = validateEdgerV2PolicyModel(JSON.parse(fs.readFileSync(args.model, "utf8")));
const report = JSON.parse(fs.readFileSync(args.report, "utf8"));
if (report.schema_version !== EDGER_V2_EVALUATION_REPORT_SCHEMA) {
  throw new Error(`report schema must be ${EDGER_V2_EVALUATION_REPORT_SCHEMA}`);
}
if (report.profile !== "full") {
  throw new Error("only a full evaluation profile can be promoted");
}
if (report.candidate_model_id !== model.model_id) {
  throw new Error("evaluation report model ID does not match candidate");
}
if (report.candidate_artifact_checksum !== sha256File(args.model)) {
  throw new Error("evaluation report artifact checksum does not match candidate");
}
const failedGates = REQUIRED_GATES.filter((name) => report.gates?.[name]?.passed !== true);
if (!report.promotion?.passed || failedGates.length > 0) {
  throw new Error(
    `v2 promotion refused; failed gates: ${[
      ...failedGates,
      ...(report.promotion?.failures ?? []),
    ].join("; ")}`,
  );
}

const promotedReport = {
  ...report,
  promoted_model_id: model.model_id,
  promoted_artifact: PROMOTED_MODEL,
  promoted_artifact_checksum: report.candidate_artifact_checksum,
  promotion_report_checksum: sha256File(args.report),
};
const reference = createEdgerV2ReferenceReport(promotedReport);
fs.mkdirSync(path.dirname(path.resolve(PROMOTED_MODEL)), { recursive: true });
fs.copyFileSync(args.model, PROMOTED_MODEL);
if (sha256File(PROMOTED_MODEL) !== report.candidate_artifact_checksum) {
  throw new Error("promoted artifact copy does not match the evaluated candidate checksum");
}
writeJson(PROMOTED_REPORT, promotedReport);
writeJson(PROMOTED_REFERENCE, reference);
fs.writeFileSync(
  GENERATED_MODEL,
  `// Generated by scripts/edger-v2-promote.mjs from ${PROMOTED_MODEL}.\n` +
    "// Reviewed v2 promotion; do not edit generated weights by hand.\n" +
    `export const EDGER_POLICY_MODEL = ${JSON.stringify(canonical(model), null, 2)};\n\n` +
    "export default EDGER_POLICY_MODEL;\n",
);
console.log(`promoted ${model.model_id}`);
console.log(`wrote ${PROMOTED_MODEL}`);
console.log(`wrote ${PROMOTED_REPORT}`);
console.log(`wrote ${PROMOTED_REFERENCE}`);
console.log(`wrote ${GENERATED_MODEL}`);
